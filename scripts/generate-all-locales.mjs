// Offline locale generator: writes `lib/locales.generated.ts` from BCP-47 tags
// without calling the CMS. Same output shape as generate-locales.mjs.
//
// Usage: node scripts/generate-all-locales.mjs [--set markets|languages|likely|all]
//        [--tags fr-CA,de-AT] [--route-segment tag|lower]
// Default set is "all" (markets + languages + likely region variants).
//
// Note: this overwrites the CMS-derived file, and `npm run dev/build` re-runs
// gen:locales first, so run this afterwards (or point gen:locales elsewhere).

import { writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveTags, displayName } from './bcp47.mjs';

const OUT_FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'locales.generated.ts');
const DEFAULT_LOCALE = process.env.OPTIMIZELY_DEFAULT_LOCALE || 'en';

const opts = { set: 'all', tags: null, routeSegment: 'tag' };
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--set') opts.set = argv[++i];
  else if (argv[i] === '--tags') opts.tags = (argv[++i] ?? '').split(',').map((t) => t.trim()).filter(Boolean);
  else if (argv[i] === '--route-segment') opts.routeSegment = argv[++i];
  else { console.error(`Unknown argument: ${argv[i]}`); process.exit(1); }
}
if (!['markets', 'languages', 'likely', 'all'].includes(opts.set)) {
  console.error(`Invalid --set "${opts.set}"`);
  process.exit(1);
}

let tags;
try {
  tags = resolveTags(opts);
} catch (err) {
  console.error('[gen:all-locales]', err.message);
  process.exit(1);
}
if (!tags.includes(DEFAULT_LOCALE)) tags.push(DEFAULT_LOCALE);
tags.sort((a, b) => (a === DEFAULT_LOCALE ? -1 : b === DEFAULT_LOCALE ? 1 : a.localeCompare(b)));

const locales = tags.map((key) => ({
  key,
  displayName: displayName(key),
  routeSegment: key === DEFAULT_LOCALE ? '' : opts.routeSegment === 'lower' ? key.toLowerCase() : key,
}));

const out = `// AUTO-GENERATED by scripts/generate-all-locales.mjs — do not edit.
// Offline BCP-47 set ("${opts.tags ? 'custom tags' : opts.set}"), not read from the CMS.

export type Locale = {
  /** BCP-47 language tag, e.g. "en", "es", "sv-SE". */
  key: string;
  /** Human-readable name shown in the language switcher. */
  displayName: string;
  /** URL segment for routing. Empty string for the default locale (clean URLs). */
  routeSegment: string;
};

export const DEFAULT_LOCALE = ${JSON.stringify(DEFAULT_LOCALE)};

export const LOCALES: Locale[] = ${JSON.stringify(locales, null, 2)};
`;
await writeFile(OUT_FILE, out, 'utf8');
console.log(`[gen:all-locales] Wrote ${locales.length} locale(s) to ${OUT_FILE}`);
